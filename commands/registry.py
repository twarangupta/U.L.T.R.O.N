"""The command registry: every voice command is declared once, here or next to its handler.

    @command("volume_set", "Set the speaker volume to a percentage.",
             params=[Param("level", "int", "volume from 0 to 100")],
             examples=["set the volume to 40", "volume 70 percent"],
             rules=[r"(?:set )?(?:the )?volume (?:to )?(?P<level>\\d+)(?: percent)?"])
    def volume_set(level: int) -> str: ...

What a declaration feeds (D30):
- rules: anchored regexes for stage a (whole normalized sentence, named groups fill params)
- examples / not_examples: the meaning matcher in stage b (intent.py)
- description and params: the tool schema the LLM sees in stage c
- risk: safe, confirm (spoken confirm, any stage) or blocked (never runs)
- doing: what ULTRON says before a medium-impact action, so barge-in can stop it
- everything: commands.txt, generated by tools/gen_commands_txt.py

A handler gets its params as keyword arguments and returns the reply to speak
("" for a silent success). Returning None from a rule match means "not mine",
and routing goes on. Done("...") marks a success reply that can be skipped
when the action was already announced.
"""
from __future__ import annotations

import re
from contextlib import contextmanager
from dataclasses import dataclass, field
from typing import Callable

RISKS = ("safe", "confirm", "blocked")
PARAM_TYPES = ("str", "int", "app", "choice")
STAGES = ("rule", "match", "tool")
_JSON_TYPE = {"str": "string", "int": "integer", "app": "string", "choice": "string"}


class Done(str):
    """A success reply; after an announcement ("Closing Chrome.") it is not spoken again."""


class ArgumentError(ValueError):
    pass


@dataclass(frozen=True)
class Param:
    name: str
    type: str = "str"
    description: str = ""
    required: bool = True
    choices: tuple[str, ...] = ()
    # Stage b: free text is taken from after the first of these cue phrases.
    cues: tuple[str, ...] = ()

    def __post_init__(self):
        if self.type not in PARAM_TYPES:
            raise ValueError(f"param {self.name}: unknown type {self.type}")
        if self.type == "choice" and not self.choices:
            raise ValueError(f"param {self.name}: choice needs choices")


@dataclass
class Command:
    name: str
    description: str
    handler: Callable[..., str | None]
    params: tuple[Param, ...] = ()
    examples: tuple[str, ...] = ()
    not_examples: tuple[str, ...] = ()
    rules: tuple[re.Pattern, ...] = ()
    risk: str = "safe"
    doing: str | None = None          # "Closing {app}." -> announced before running
    confirm_text: str | None = None   # finishes "Say confirm to ..."
    title: str | None = None          # "close {app}", for "Did you mean ...?" and commands.txt
    stages: tuple[str, ...] = STAGES
    priority: int = 50
    group: str = "General"
    raw: bool = False                 # rules see the original wording (case and punctuation kept)

    # ---- schema and validation (stage c) ----
    def tool_schema(self) -> dict:
        props, required = {}, []
        for p in self.params:
            prop = {"type": _JSON_TYPE[p.type], "description": p.description or p.name}
            if p.choices:
                prop["enum"] = list(p.choices)
            props[p.name] = prop
            if p.required:
                required.append(p.name)
        return {"type": "function", "function": {
            "name": self.name, "description": self.description,
            "parameters": {"type": "object", "properties": props, "required": required}}}

    def validate(self, args: dict | None) -> dict:
        """Check and convert arguments; raises ArgumentError. Unknown keys are dropped."""
        args = dict(args or {})
        out = {}
        for p in self.params:
            value = args.get(p.name)
            if value is None or (isinstance(value, str) and not value.strip()):
                if p.required:
                    raise ArgumentError(f"{self.name}: missing {p.name}")
                continue
            out[p.name] = coerce(p, value)
        return out

    def describe(self, args: dict | None = None) -> str:
        """Plain words for this call: "close Chrome"."""
        text = self.title or self.name.replace("_", " ")
        values = {p.name: pretty_value(args.get(p.name)) if args and args.get(p.name) is not None else ""
                  for p in self.params}
        try:
            text = text.format(**values)
        except (KeyError, IndexError):
            pass
        return re.sub(r"\s+", " ", text).strip()


def pretty_value(value) -> str:
    if isinstance(value, str) and value.islower():
        from commands.apps import pretty
        return pretty(value)
    return str(value)


def coerce(p: Param, value):
    if p.type == "int":
        if isinstance(value, bool):
            raise ArgumentError(f"{p.name}: not a number")
        if isinstance(value, (int, float)):
            return int(value)
        from commands.slots import find_number
        number = find_number(str(value))
        if number is None:
            raise ArgumentError(f"{p.name}: not a number: {value!r}")
        return number
    text = str(value).strip().strip(".?!,").strip()
    if p.type == "choice":
        low = " ".join(text.lower().replace("_", " ").split())
        for candidate in (low, low + "s", low.replace(" ", "")):
            if candidate in p.choices:
                return candidate
        from commands.apps import fuzzy
        best = fuzzy(low, list(p.choices))
        if best is None:
            raise ArgumentError(f"{p.name}: {value!r} is not one of {p.choices}")
        return best
    if p.type == "app":
        from commands.apps import canonical
        return canonical(text)
    return text


REGISTRY: dict[str, Command] = {}


def command(name: str, description: str, *, params=(), examples=(), not_examples=(), rules=(),
            risk: str = "safe", doing: str | None = None, confirm_text: str | None = None,
            title: str | None = None, stages=STAGES, priority: int = 50, group: str = "General",
            raw: bool = False):
    """Declare a voice command (see the module docstring)."""
    if risk not in RISKS:
        raise ValueError(f"{name}: unknown risk {risk}")
    if risk == "confirm" and not confirm_text:
        raise ValueError(f"{name}: confirm commands need confirm_text")

    def register(fn):
        if name in REGISTRY:
            raise ValueError(f"duplicate command {name}")
        REGISTRY[name] = Command(
            name=name, description=description, handler=fn, params=tuple(params),
            examples=tuple(examples), not_examples=tuple(not_examples),
            rules=tuple(re.compile(r, re.IGNORECASE | re.DOTALL if raw else 0) for r in rules),
            risk=risk, doing=doing, confirm_text=confirm_text, title=title, stages=tuple(stages),
            priority=priority, group=group, raw=raw)
        return fn
    return register


def get(name: str) -> Command | None:
    return REGISTRY.get(name)


def commands(stage: str | None = None) -> list[Command]:
    """All commands, highest priority first (declaration order breaks ties)."""
    items = [c for c in REGISTRY.values() if stage is None or stage in c.stages]
    return sorted(items, key=lambda c: -c.priority)


# ---- dry run: handlers say what they would do instead of doing it ----
_dry_run = [False]


def is_dry_run() -> bool:
    return _dry_run[0]


@contextmanager
def dry_run(on: bool = True):
    old, _dry_run[0] = _dry_run[0], on
    try:
        yield
    finally:
        _dry_run[0] = old


def call(cmd: Command, args: dict) -> str | None:
    if _dry_run[0]:
        shown = ", ".join(f"{k}={v!r}" for k, v in args.items())
        return Done(f"Would run {cmd.name}({shown}).")
    return cmd.handler(**args)


@dataclass
class Example:
    """A sentence and the command it means, for the matcher index."""
    text: str
    command: str | None  # None: not a command
    extra: dict = field(default_factory=dict)
